function workflow(topic, output) {
  return [
    {
      title: '明确任务',
      action: `把“我想学 ${topic}”改写成具体目标：要解决什么问题、用什么材料、最后交付什么。`,
      check: `检查点：能不能用一句话说清本轮要得到的 ${output}。`
    },
    {
      title: '输入材料',
      action: '把题目、草稿、资料、经历、时间限制或评价标准一次性放进对话。',
      check: '检查点：AI 不需要猜你的背景，也不需要凭空补事实。'
    },
    {
      title: '先做诊断',
      action: '要求 AI 先判断问题类型、薄弱点和风险，不要立刻生成最终答案。',
      check: '检查点：你能看到“为什么现在做不好”，而不仅是得到一版成品。'
    },
    {
      title: '分步操作',
      action: '按提示、示范、练习、反馈的顺序推进，每轮只解决一个关键问题。',
      check: '检查点：每一步都有你的输入或选择，而不是 AI 单方面输出。'
    },
    {
      title: '产出成品',
      action: `把 AI 的建议改成自己的版本，形成可提交、可展示或可复用的 ${output}。`,
      check: '检查点：最终内容能解释来源、理由和取舍。'
    },
    {
      title: '复盘迁移',
      action:
        '记录哪一句 Prompt 最有效、哪类错误最常出现，以及下一次如何改进。',
      check: '检查点：下次遇到相似任务时，你不需要从零开始。'
    }
  ]
}

function templates(topic, output, role = '学习教练') {
  return [
    {
      title: '诊断模板',
      body: `你是我的${role}。\n我正在处理的任务是：${topic}。\n我的当前情况是：【写清基础、材料、限制】。\n请先不要直接给最终答案。\n请判断：1. 我真正卡在哪里；2. 需要补充哪些信息；3. 下一步最小练习是什么。`
    },
    {
      title: '操作模板',
      body: `请基于我提供的材料，帮我完成一轮实操。\n要求：\n1. 只使用我提供的材料，不编造事实。\n2. 先给步骤，再给示范。\n3. 每一步都说明判断标准。\n4. 最后输出一份可修改的 ${output}。`
    },
    {
      title: '复盘模板',
      body: `这是我的最终产出和过程记录：\n【粘贴你的版本和关键对话】\n请帮我复盘：\n1. 哪一步最有效？\n2. 哪个问题仍然没有解决？\n3. 下一次遇到类似任务，我应该怎样改 Prompt？\n4. 请给我一个 20 分钟内能完成的巩固任务。`
    }
  ]
}

function mistakes(topic) {
  return [
    {
      wrong: '一上来就要最终答案',
      reason: `这样会跳过 ${topic} 中最重要的诊断和练习过程，看似省时间，实际很难迁移。`,
      fix: '先要求 AI 判断卡点、提出问题或给第一步提示。'
    },
    {
      wrong: '不提供原始材料',
      reason: 'AI 只能根据通用经验回答，结果容易漂亮但不贴合你的真实任务。',
      fix: '把题目、草稿、资料、目标、时间和评价标准都放进去。'
    },
    {
      wrong: '不做第二轮追问',
      reason:
        '第一版输出通常只是框架，真正有价值的部分来自纠偏、补证据和压缩范围。',
      fix: '针对最不满意的一点继续追问，而不是重新开一个新问题。'
    }
  ]
}

function build(spec) {
  return {
    title: spec.title,
    subtitle: spec.subtitle,
    audience: spec.audience,
    duration: spec.duration ?? '60-90 分钟',
    output: spec.output,
    scenario: spec.scenario,
    rawMaterial: spec.rawMaterial,
    badMove: spec.badMove,
    badPrompt: spec.badPrompt,
    badResult: spec.badResult,
    goodPrompt: spec.goodPrompt,
    sampleOutput: spec.sampleOutput,
    followUpPrompt: spec.followUpPrompt,
    followUpResult: spec.followUpResult,
    workflow: spec.workflow ?? workflow(spec.topic, spec.output),
    tools: spec.tools ?? commonTools,
    templates: spec.templates ?? templates(spec.topic, spec.output, spec.role),
    mistakes: spec.mistakes ?? mistakes(spec.topic),
    assignments: spec.assignments,
    reflections: spec.reflections,
    boundary: boundaries[spec.boundary ?? 'study']
  }
}

